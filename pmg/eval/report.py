"""Markdown/JSON rendering of an EvalReport (piece 4).

``render_report`` turns an :class:`EvalReport` into the metrics table the
README shows: one row per canonical metric (``pmg.contracts.METRIC_NAMES``
order and descriptions), deterministic value formatting (floats with two
decimals, booleans as a check/cross mark, ``None`` as an em dash), followed
by a Detail section with the timeline match table, action-item best pairs,
honesty verdicts and the introducer sha tokens considered.

``save_report`` writes ``eval_report.json`` (the machine-readable report)
and ``metrics.md`` (the human-readable one) and returns both paths.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

from pmg.contracts import METRIC_NAMES, EvalReport

__all__ = ["render_report", "save_report"]


def _fmt(value: Any) -> str:
    """Format a metric value for the table: None -> em dash, bool -> check
    or cross, float -> 2 decimals, anything else -> str(value)."""
    if value is None:
        return "—"
    if isinstance(value, bool):
        return "✓" if value else "✗"
    if isinstance(value, float):
        return f"{value:.2f}"
    return str(value)


def _cell(text: Any) -> str:
    """Make *text* safe for one markdown table cell."""
    return str(text if text is not None else "—").replace("|", "\\|").replace("\n", " ")


def _summary_line(report: EvalReport) -> str:
    intro = report.metric("introducer_top1")
    if intro is True:
        intro_txt = "EXACT ✓"
    elif report.metric("introducer_top5") is True:
        intro_txt = "TOP5 ✓"
    else:
        intro_txt = "MISS ✗"
    recall = report.metric("timeline_recall")
    recall_txt = f"{recall:.2f}" if isinstance(recall, float) else "—"
    honest = report.metric("honesty_check")
    honest_txt = "yes" if honest is True else "no"
    return f"introducer: {intro_txt} · timeline recall {recall_txt} · honest: {honest_txt}"


def _detail_section(detail: dict[str, Any]) -> list[str]:
    """Render the known detail fragments; unknown/absent keys are skipped."""
    lines: list[str] = ["## Detail", ""]

    intro = detail.get("introducer") or {}
    if intro:
        lines.append(
            f"- Introducer: gt sha10 `{intro.get('gt_sha10', '—')}`; sha10 tokens "
            f"considered (root_cause, in order): "
            f"{', '.join(f'`{t}`' for t in intro.get('sha_tokens_considered', [])) or '—'}"
        )

    linkage = detail.get("claim_linkage") or {}
    if linkage:
        lines.append(
            f"- Claim linkage: {linkage.get('valid', 0)}/{linkage.get('total', 0)} — "
            f"{linkage.get('mode', '—')}"
        )

    lines_blob = detail.get("line_agreement") or {}
    if lines_blob and lines_blob.get("total") is not None:
        lines.append(
            f"- Line agreement: {lines_blob.get('matched', 0)}/{lines_blob.get('total', 0)} "
            f"human sentences matched (jaccard ≥ {lines_blob.get('jaccard_threshold', 0.35)})"
        )

    honesty = detail.get("honesty") or {}
    if honesty:
        lines.append("")
        lines.append("### Honesty verdicts")
        lines.append("")
        for sid, verdict in honesty.items():
            mark = "PASS" if verdict.get("pass") else "FAIL"
            lines.append(f"- **{sid}**: {mark} — {verdict.get('reason', '')}")
        lines.append("")

    timeline = detail.get("timeline") or {}
    table = timeline.get("gt_events") or []
    if timeline:
        lines.append("### Timeline match table (gt event → generated entry)")
        lines.append("")
        lines.append("| GT date | GT event | Matched generated entry | Rule |")
        lines.append("|---|---|---|---|")
        for row in table:
            lines.append(
                f"| {_cell(row.get('gt_date'))} | {_cell(row.get('gt_event'))} "
                f"| {_cell(row.get('matched_generated'))} | {_cell(row.get('rule'))} |"
            )
        lines.append("")

    pairs = (detail.get("action_items") or {}).get("pairs") or []
    if detail.get("action_items"):
        lines.append("### Action item best pairs")
        lines.append("")
        lines.append("| GT action item | Best generated item | Score | Covered |")
        lines.append("|---|---|---|---|")
        for pair in pairs:
            lines.append(
                f"| {_cell(pair.get('gt_item'))} | {_cell(pair.get('best_generated'))} "
                f"| {_fmt(pair.get('best_score'))} | {_fmt(pair.get('covered'))} |"
            )
        lines.append("")
    return lines


def render_report(report: EvalReport) -> str:
    """Render *report* as the standalone metrics markdown document."""
    by_name = {m.name: m for m in report.metrics}
    lines: list[str] = [
        f"# Postmortem evaluation: {report.case}",
        "",
        f"Generated by: `{report.generated_by}` — deterministic, AI-free evaluation "
        f"(heuristics documented per metric below).",
        "",
        f"**{_summary_line(report)}**",
        "",
        "| Metric | Description | Value | Notes |",
        "|---|---|---|---|",
    ]
    for name, description in METRIC_NAMES.items():
        metric = by_name.get(name)
        if metric is None:
            lines.append(f"| {name} | {description} | — | not computed |")
        else:
            lines.append(f"| {name} | {description} | {_fmt(metric.value)} | {_cell(metric.detail)} |")
    lines.append("")
    lines.extend(_detail_section(report.detail or {}))
    return "\n".join(lines).rstrip() + "\n"


def save_report(report: EvalReport, out_dir: Path) -> tuple[Path, Path]:
    """Write ``eval_report.json`` + ``metrics.md`` into *out_dir* (created if
    needed) and return the two paths, JSON first."""
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    json_path = out_dir / "eval_report.json"
    report.save(json_path)
    md_path = out_dir / "metrics.md"
    md_path.write_text(render_report(report), encoding="utf-8")
    return json_path, md_path
